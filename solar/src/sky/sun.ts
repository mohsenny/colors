/** The Sun's colour at `temperature`, from Planck's law through the eye's response, white now. */
export function sunTint(temperature: number): [number, number, number] {
  const T = Math.max(TINT[0][0], Math.min(TINT[TINT.length - 1][0], temperature))
  const i = Math.max(1, TINT.findIndex(([at]) => at >= T))
  const [lo, hi] = [TINT[i - 1], TINT[i]]
  const f = Math.log(T / lo[0]) / Math.log(hi[0] / lo[0])
  return [lo[1] + (hi[1] - lo[1]) * f, lo[2] + (hi[2] - lo[2]) * f, lo[3] + (hi[3] - lo[3]) * f]
}
