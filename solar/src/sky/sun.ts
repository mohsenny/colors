/** How far out the Moon is, as a share of how far it is now. */
export function moonWidening(ms: number): number {
  const t = gyrOf(ms)
  const i = Math.max(1, Math.min(MOON.length - 1, MOON.findIndex(([at]) => at > t) >>> 0))
  const [[t0, a0], [t1, a1]] = [MOON[i - 1], MOON[i]]
  const f = Math.max(0, Math.min(1, (t - t0) / (t1 - t0)))
  return (a0 + (a1 - a0) * f) / 60.3
}

