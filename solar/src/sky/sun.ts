function gyrOf(ms: number): number {
  return (ms - J2000_MS) / YEAR_MS / 1e9
}

/** The row `t` falls in, the first or last past either end. */
function rowAt(t: number): number {
  let [lo, hi] = [0, TRACK.length - 1]
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1
    if (TRACK[mid][0] <= t) lo = mid
    else hi = mid
  }
  return lo
}

export function sunAt(ms: number): SunState {
  const t = gyrOf(ms)
  const i = rowAt(t)
  const [t0, L0, R0, M0] = TRACK[i]
  const [t1, L1, R1, M1] = TRACK[i + 1]
  const f = Math.max(0, Math.min(1, (t - t0) / (t1 - t0)))
  // Light and size change by powers, so between rows they go evenly in their logs.
  const luminosity = L0 * (L1 / L0) ** f
  const R = R0 * (R1 / R0) ** f
  return { radius: R * R_KM, temperature: T_NOW * (luminosity / (R * R)) ** 0.25, luminosity, mass: M0 + (M1 - M0) * f }
}

/** When the swelling Sun takes each planet it takes, billion years on, and how far out that planet is now, au. */
const ENGULF: Partial<Record<BodyId, [number, number]>> = {
  mercury: [7.5857, 0.387],
  venus: [7.5885, 0.723],
  earth: [7.5895, 1],
}

/** The last years a planet is dragged in over, through the Sun's thin outside, billion. */
const DRAG = 0.001

/** Where each of them ends: the Sun's edge, as a share of how far out it is now. */
const END = new Map(Object.entries(ENGULF).map(([id, [t, a]]) => [id, sunAt(J2000_MS + t * 1e9 * YEAR_MS).radius / (a * AU_KM)]))

/** Whether the Sun has taken `id` by `ms`. The Moon goes with the Earth. */
export function engulfed(id: BodyId, ms: number): boolean {
  const e = ENGULF[id === 'moon' ? 'earth' : id]
  return e !== undefined && gyrOf(ms) >= e[0]
}

/**
 * How far out a planet's orbit is, as a share of how far it is now: as the
 * Sun loses mass its hold loosens and every orbit widens with it, until the
 * planets it takes are dragged in to its edge.
 */
export function widening(id: BodyId, ms: number): number {
  const t = gyrOf(ms)
  const wide = 1 / sunAt(ms).mass
  const e = ENGULF[id]
  if (!e) return wide
  const f = Math.max(0, Math.min(1, 1 - (e[0] - t) / DRAG)) ** 2
  return wide + ((END.get(id) as number) - wide) * f
}

