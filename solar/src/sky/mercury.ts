function sum(series: Series, t: number): number {
  let s = 0
  for (let k = series.length - 1; k >= 0; k--) {
    let w = 0
    for (const [a, b, c] of series[k]) w += a * Math.cos(b + c * t)
    s = s * t + w
  }
  return s
}

/** Mercury from the Sun's centre, au, on the Earth's equator of J2000 as Astronomy Engine gives the other planets, `tt` days from J2000. */
export function mercuryAt(tt: number): { x: number; y: number; z: number } {
  const t = tt / 365_250
  const [l, b, r] = [sum(LONGITUDE, t), sum(LATITUDE, t), sum(DISTANCE, t)]
  const [x, y, z] = [r * Math.cos(b) * Math.cos(l), r * Math.cos(b) * Math.sin(l), r * Math.sin(b)]
  // Off the ecliptic onto the equator, as Astronomy Engine turns its own.
  return { x: x + 4.4036e-7 * y - 1.90919e-7 * z, y: -4.79966e-7 * x + 0.917482137087 * y - 0.397776982902 * z, z: 0.397776982902 * y + 0.917482137087 * z }
}
